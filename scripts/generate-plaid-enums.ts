// Regenerates src/common/lib/plaid-enums.ts from the installed Plaid SDK
// (node_modules/plaid/dist/api.d.ts). Run from the repo root after a Plaid
// SDK upgrade, then run `bun tsc --noEmit` and the client test suite — a
// value that moved in the SDK shows up as a type error or a failing test,
// not a silent bundle change.
//
//   bun scripts/generate-plaid-enums.ts
//
// The generated module is the client layer's only contact with the Plaid
// SDK: it declares the enums the client/common code uses in value position
// as frozen constant objects plus string-literal union types, and re-exports
// the interfaces as types. Importing the enums from here instead of `plaid`
// keeps the 400+ kB SDK (and the axios it drags in) out of the browser
// bundle; see issue 847.
import { readFileSync, writeFileSync } from "fs";
import { dirname, join } from "path";
import { fileURLToPath } from "url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const ENUMS = [
  "AccountType",
  "AccountSubtype",
  "AccountBaseVerificationStatusEnum",
  "CountryCode",
  "Products",
  "TransactionCode",
  "TransactionPaymentChannelEnum",
  "TransactionTransactionTypeEnum",
  "InvestmentTransactionType",
  "InvestmentTransactionSubtype",
];

// Interfaces the client/common layers use only as types. They are
// re-exported from the SDK as types, so the bundler erases them.
const TYPE_REEXPORTS = [
  "AccountBalance",
  "FixedIncome",
  "Holding",
  "Institution",
  "InstitutionStatus",
  "InvestmentTransaction",
  "Location",
  "OptionContract",
  "PaymentMeta",
  "PersonalFinanceCategory",
  "PlaidError",
  "Security",
  "Transaction",
];

const dts = readFileSync(join(ROOT, "node_modules/plaid/dist/api.d.ts"), "utf8");

const out: string[] = [];
out.push(`/**`);
out.push(` * Plaid enum values the client and common layers use, declared locally`);
out.push(` * so the browser bundle does not pull in the Plaid Node SDK (see issue 847).`);
out.push(` *`);
out.push(` * Generated by scripts/generate-plaid-enums.ts from the installed SDK —`);
out.push(` * do not edit by hand. Each enum is a frozen constant object plus the`);
out.push(` * string-literal union of its values. Server code keeps importing`);
out.push(` * \`plaid\` directly.`);
out.push(` *`);
out.push(` * The remaining \`plaid\` names the client layer needs (interfaces such as`);
out.push(` * \`Transaction\` and \`AccountBalance\`) are type-only here: they are`);
out.push(` * re-exported as types from the SDK, so the bundler erases them and they`);
out.push(` * contribute nothing to the client bundle.`);
out.push(` */`);
out.push(``);

for (const name of ENUMS) {
  const re = new RegExp(`export declare enum ${name} \\{([^}]*)\\}`, "s");
  const m = dts.match(re);
  if (!m) throw new Error(`enum ${name} not found in node_modules/plaid/dist/api.d.ts`);
  const members: [string, string][] = [];
  for (const line of m[1].split("\n")) {
    const mm = line.match(/^\s*([A-Za-z0-9_]+)\s*=\s*"((?:[^"\\]|\\.)*)"/);
    if (mm) members.push([mm[1], mm[2]]);
  }
  if (members.length === 0) throw new Error(`enum ${name}: no members parsed`);
  out.push(`export const ${name} = Object.freeze({`);
  for (const [k, v] of members) out.push(`  ${k}: ${JSON.stringify(v)},`);
  out.push(`} as const);`);
  out.push(`export type ${name} = (typeof ${name})[keyof typeof ${name}];`);
  out.push(``);
  console.log(`${name}: ${members.length} members`);
}

out.push(`export type {`);
for (const name of TYPE_REEXPORTS) out.push(`  ${name},`);
out.push(`} from "plaid";`);
out.push(``);

const target = join(ROOT, "src/common/lib/plaid-enums.ts");
writeFileSync(target, out.join("\n"));
console.log(`wrote ${target}`);
